#!/usr/bin/env python3
"""Rebuild reviewable indexes from the current contract and forward SQL migrations.

Use --check in CI. This updates documentation/status indexes, never applies migrations.
"""
from pathlib import Path
import argparse
import csv
import io
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    spec = json.loads((ROOT / 'contracts/openapi.json').read_text(encoding='utf-8'))
    modules = json.loads((ROOT / 'contracts/modules.json').read_text(encoding='utf-8'))
    operations = [(path, method, operation) for path, methods in spec['paths'].items()
                  for method, operation in methods.items()]
    for module in modules:
        implemented = [operation for _, _, operation in operations
                       if operation['tags'][0] == module['id'] and operation['x-status'] == 'implemented']
        module['status'] = 'partial' if implemented else 'planned'
    done = sum(operation['x-status'] == 'implemented' for _, _, operation in operations)
    lines = ['# 当前 API 与模块索引', '',
             '<!-- Generated by scripts/sync_contract_index.py; edit OpenAPI first. -->', '',
             f"契约版本 **{spec['info']['version']}**：{len(operations)} 个操作，{done} 个已实现，{len(operations)-done} 个规划；{len(spec['components']['schemas'])} 个 Schema。", '',
             '机器契约：[openapi.json](openapi.json)。`implemented` 表示对应后端路由存在并纳入验证；运行配置、权限和格式仍须满足。`partial` 表示该模块完整产品范围尚未完成，不能把接口数量当作课程完成率。', '',
             '逐模块已做/未做/下一步见 [开发接手指南](../docs/02-modules.md)，实际验证见 [当前验收](../evidence/runtime-review.md)。', '',
             '| 模块 | 名称 | 状态 | 已实现操作 | 规划操作 |',
             '|---|---|---|---:|---:|']
    for module in modules:
        items = [operation for _, _, operation in operations if operation['tags'][0] == module['id']]
        count = sum(operation['x-status'] == 'implemented' for operation in items)
        lines.append(f"| {module['id']} | {module['name']} | {module['status']} | {count} | {len(items)-count} |")
    lines += ['', '## 操作清单', '', '所有路径省略 `/api/v1`。下载为真实文件响应，其余按 OpenAPI 的准确 DTO。', '',
              '| 方法 | 路径 | operationId | 模块 | 状态 |', '|---|---|---|---|---|']
    for path, method, operation in operations:
        lines.append(f"| {method.upper()} | `{path}` | `{operation['operationId']}` | {operation['tags'][0]} | {operation['x-status']} |")
    trace_path = ROOT / 'evidence/traceability.csv'
    with trace_path.open(encoding='utf-8', newline='') as stream:
        reader = csv.DictReader(stream)
        fields = reader.fieldnames
        trace = list(reader)
    for row in trace:
        row['operation_ids'] = ';'.join(operation['operationId'] for _, _, operation in operations
                                       if operation['tags'][0] == row['module'])
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator='\n')
    writer.writeheader()
    writer.writerows(trace)
    tables = {}
    migration_names = []
    for path in sorted((ROOT / 'database').glob('V*.sql')):
        migration_names.append(path.name)
        sql = path.read_text(encoding='utf-8')
        for name, body, description in re.findall(r"CREATE TABLE (\w+) \((.*?)\) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin(?: COMMENT(?:=| )'([^']*)')?;", sql, re.S):
            if name in tables:
                raise ValueError('Duplicate table: ' + name)
            columns, constraints = [], []
            for raw in body.splitlines():
                line = raw.strip().rstrip(',')
                if not line:
                    continue
                match = re.match(r"([a-z][a-z0-9_]*) (.+?)(?: COMMENT '((?:''|[^'])*)')?$", line)
                if match:
                    columns.append((match.group(1), match.group(2), match.group(3) or '字段用途见所属服务及迁移。', path.name))
                else:
                    constraints.append(line)
            tables[name] = {'description': description or '持久运行数据', 'columns': columns,
                            'constraints': constraints, 'migration': path.name}
        for name, column, definition, description in re.findall(r"ALTER TABLE (\w+) ADD COLUMN (\w+) (.+?) COMMENT '([^']*)';", sql):
            tables[name]['columns'].append((column, definition, description, path.name))
        for name, constraint in re.findall(r'ALTER TABLE (\w+) ADD CONSTRAINT (.*?);', sql, re.S):
            tables[name]['constraints'].append(constraint)
        for unique, index, name, columns in re.findall(r'CREATE (UNIQUE )?INDEX (\w+) ON (\w+)\(([^;]+)\);', sql):
            tables[name]['constraints'].append(f'{unique}INDEX {index} ({columns})')
    dictionary = ['# 当前数据库字段字典', '',
                  '<!-- Generated by scripts/sync_contract_index.py from cumulative forward migrations. -->', '',
                  f"共 **{len(tables)} 张业务表**；不含 Flyway 元数据表。迁移为 {'、'.join(migration_names)}。", '',
                  '这是累积到当前版本的唯一字段字典。已发布迁移不可修改或删除；新增字段使用下一条前向迁移。UUID 为 CHAR(36)，哈希为 SHA-256，时间由服务按 UTC 写入。跨表归属、完整来源闭包、语义正确性仍由服务和事务验证，不能仅凭外键判断。', '',
                  '具体事务、审核、撤回与运行规则见 [数据与一致性](../docs/03-data.md)。', '']
    for name, table in tables.items():
        dictionary += [f"## {name} — {table['description']}", '', f"创建于 `{table['migration']}`。", '',
                       '| 字段 | SQL 定义 | 用途 | 引入迁移 |', '|---|---|---|---|']
        for column, definition, description, migration in table['columns']:
            dictionary.append(f'| `{column}` | `{definition}` | {description.replace(chr(124), chr(92)+chr(124))} | `{migration}` |')
        if table['constraints']:
            dictionary += ['', '约束与索引：', '', '```sql', *table['constraints'], '```']
        dictionary.append('')
    return {
        'contracts/modules.json': json.dumps(modules, ensure_ascii=False, indent=2) + '\n',
        'contracts/README.md': '\n'.join(lines) + '\n',
        'database/data-dictionary.md': '\n'.join(dictionary).rstrip() + '\n',
        'evidence/traceability.csv': stream.getvalue(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for relative, content in generated_files().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(relative)
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        raise SystemExit('Indexes are stale; run python scripts/sync_contract_index.py: ' + ', '.join(stale))
    print('Current contract, module, table and traceability indexes are synchronized.')


if __name__ == '__main__':
    main()
